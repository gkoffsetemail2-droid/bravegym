function buildInitialLockers(): Locker[] {
  const lockers: Locker[] = [];
  for (let i = 1; i <= 24; i++) {
    const num = String(i).padStart(2, '0');
    lockers.push({
      number: num,
      zone: i <= 12 ? 'North Wing' : 'South Wing',
      size: i % 4 === 0 ? 'Tall' : 'Standard',
      status: i === 18 ? 'maintenance' : 'operational',
    });
  }
  return lockers;
}

